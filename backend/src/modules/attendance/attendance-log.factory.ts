import type { AttendanceLog } from './entities/attendance-log.entity';

/** A new attendance row for one person and IST date: no punches yet, status ABSENT unless `fields` says otherwise. */
export function newAttendanceLog(
  id: string,
  staffId: string,
  date: string,
  now: Date,
  fields: Partial<AttendanceLog>,
): AttendanceLog {
  return {
    id,
    staffId,
    attendanceDate: date,
    wardId: null,
    officeId: null,
    assignmentId: null,
    shiftType: null,
    status: 'ABSENT',
    isLate: false,
    lateMinutes: 0,
    workedMinutes: null,
    checkinClientUuid: null,
    checkinAt: null,
    checkinLat: null,
    checkinLng: null,
    checkinAccuracyM: null,
    checkinInGeofence: false,
    checkinDistanceM: null,
    checkinIsMocked: false,
    checkinChallengeId: null,
    checkinFaceScore: null,
    checkinFacePassed: false,
    checkinMode: null,
    checkinMarkedById: null,
    checkoutClientUuid: null,
    checkoutAt: null,
    checkoutLat: null,
    checkoutLng: null,
    checkoutAccuracyM: null,
    checkoutInGeofence: null,
    checkoutType: null,
    checkoutMode: null,
    checkoutMarkedById: null,
    isSuspicious: false,
    notes: null,
    version: 1,
    createdAt: now,
    updatedAt: now,
    ...fields,
  };
}
